#!/usr/bin/env node
/**
 * Generates packages/shared/icons.generated.js from lucide-static (ISC) for a curated icon set.
 * Only listed icons ship, so bundles stay small. Add a name to ICONS and re-run:
 *   node scripts/build-icons.js
 * Browse names at https://lucide.dev/icons
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const iconDir = path.join(root, 'node_modules', 'lucide-static', 'icons');
const outFile = path.join(root, 'packages', 'shared', 'icons.generated.js');

export const ICONS = [
  // Navigation & hubs
  'house', 'music', 'code', 'gamepad-2', 'audio-waveform', 'layout-dashboard', 'menu', 'command',
  // Actions
  'download', 'upload', 'play', 'pause', 'square', 'search', 'x', 'check', 'copy', 'plus', 'minus',
  'trash-2', 'refresh-cw', 'external-link', 'link', 'arrow-right', 'chevron-right', 'chevron-down', 'chevron-left',
  // Status & feedback
  'circle-check', 'circle-x', 'triangle-alert', 'info', 'loader-circle', 'activity', 'clock',
  // Domain
  'settings', 'user', 'lock', 'key-round', 'shield-check', 'zap', 'server', 'database', 'cloud', 'terminal',
  'dice-5', 'smartphone', 'calculator', 'sun', 'moon', 'credit-card', 'mail', 'qr-code', 'globe',
  'chart-column', 'file-audio', 'headphones', 'mic', 'disc-3', 'trophy', 'list', 'book-open', 'archive',
  'clipboard-paste', 'film', 'coffee', 'tag', 'gift',
  // Games: hardware, setup and dashboard tabs
  'radar', 'sliders-horizontal', 'sliders-vertical', 'cable', 'usb', 'wifi', 'bluetooth', 'crosshair',
  'keyboard', 'mouse', 'star', 'bot', 'file-code', 'message-circle', 'monitor', 'audio-lines',
];

const extractInner = (svg) => {
  const m = svg.match(/<svg[^>]*>([\s\S]*?)<\/svg>/);
  if (!m) throw new Error('Unexpected SVG format');
  return m[1].replace(/\s*\n\s*/g, '').trim();
};

const entries = ICONS.map((name) => {
  const file = path.join(iconDir, `${name}.svg`);
  if (!fs.existsSync(file)) throw new Error(`Unknown Lucide icon "${name}" (not in lucide-static)`);
  return `  ${JSON.stringify(name)}: ${JSON.stringify(extractInner(fs.readFileSync(file, 'utf8')))},`;
});

const version = JSON.parse(fs.readFileSync(path.join(root, 'node_modules', 'lucide-static', 'package.json'), 'utf8')).version;
const out = `// AUTO-GENERATED by scripts/build-icons.js from lucide-static v${version} (ISC). Do not edit by hand.
export const ICON_PATHS = {
${entries.join('\n')}
};
`;
fs.writeFileSync(outFile, out);
console.log(`Wrote ${ICONS.length} icons to ${path.relative(root, outFile)}`);
